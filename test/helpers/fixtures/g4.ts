/**
 * Fixtures for units/conversions, ice, actions, translations and tags tests.
 */
import { randomBytes } from 'node:crypto';
import prisma from '../../../prisma/prisma';
import { seedGlass } from '../dbFixtures';

function suffix(): string {
  return randomBytes(4).toString('hex');
}

export function seedUnit(workspaceId: string, name = `unit-${suffix()}`) {
  return prisma.unit.create({ data: { name, workspaceId } });
}

export function seedConversion(workspaceId: string, fromUnitId: string, toUnitId: string, factor: number, autoGenerated = false) {
  return prisma.unitConversion.create({ data: { workspaceId, fromUnitId, toUnitId, factor, autoGenerated } });
}

export function seedAction(workspaceId: string, overrides: { name?: string; actionGroup?: string } = {}) {
  return prisma.workspaceCocktailRecipeStepAction.create({
    data: { name: overrides.name ?? `action-${suffix()}`, actionGroup: overrides.actionGroup ?? 'MIXING', workspaceId },
  });
}

/** A cocktail with one step using `actionId` and (optionally) one ingredient measured in `unitId`. */
export async function seedCocktailUsing(workspaceId: string, refs: { actionId: string; unitId?: string }) {
  const glass = await seedGlass(workspaceId);
  const ingredient = await prisma.ingredient.create({ data: { name: `ingredient-${suffix()}`, workspaceId } });
  return prisma.cocktailRecipe.create({
    data: {
      name: `cocktail-${suffix()}`,
      workspaceId,
      glassId: glass.id,
      steps: {
        create: {
          stepNumber: 0,
          actionId: refs.actionId,
          ingredients: refs.unitId ? { create: { ingredientNumber: 0, amount: 4, unitId: refs.unitId, ingredientId: ingredient.id } } : undefined,
        },
      },
    },
  });
}

export function seedTagCategory(workspaceId: string, overrides: { name?: string; order?: number } = {}) {
  return prisma.tagCategory.create({ data: { workspaceId, name: { de: overrides.name ?? `category-${suffix()}` }, order: overrides.order ?? 0 } });
}

export async function readTranslationBlob(workspaceId: string): Promise<Record<string, Record<string, string>>> {
  const row = await prisma.workspaceSetting.findFirst({ where: { workspaceId, setting: 'translations' } });
  return JSON.parse(row?.value ?? '{}');
}

/** All conversions of a workspace as `from->to` keys, for duplicate/consistency checks. */
export async function conversionPairs(workspaceId: string) {
  const rows = await prisma.unitConversion.findMany({ where: { workspaceId } });
  return { rows, keys: rows.map((row) => `${row.fromUnitId}->${row.toUnitId}`) };
}
