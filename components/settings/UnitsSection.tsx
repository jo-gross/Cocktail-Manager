import React, { useCallback, useContext, useEffect, useState } from 'react';
import { useTranslation } from 'react-i18next';
import { FaChevronDown, FaPlus, FaTrashAlt } from 'react-icons/fa';
import { Button, cn, Loading, SkeletonTableRows, Table, TableBody, TableCell, TableHead, TableHeaderCell, TableRow } from '@components/ui';
import UnitModal from '@components/modals/UnitModal';
import UnitConversionModal from '@components/modals/UnitConversionModal';
import { DeleteConfirmationModal } from '@components/modals/DeleteConfirmationModal';
import { UserContext } from '@lib/context/UserContextProvider';
import { ModalContext } from '@lib/context/ModalContextProvider';
import { alertService } from '@lib/alertService';
import { alertApiV1Error } from '@lib/network/apiV1';
import { deleteUnit, deleteUnitConversion, fetchUnitConversions, fetchUnits } from '@lib/network/units';
import type { UnitConversionDto, UnitDto } from '@lib/schemas/units';
import { EntityTranslationCells, EntityTranslationHeaderCells, useLabelLocales } from './EntityTranslationLabels';
import { SettingsSection } from './SettingsSection';

const formatFactor = (value: number) => value.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });

/** Units and the conversions between them (manual + auto-generated). */
export function UnitsSection({ workspaceId }: { workspaceId: string }) {
  const labelLocales = useLabelLocales();
  const { t } = useTranslation(['settings', 'common', 'errors']);
  const userContext = useContext(UserContext);
  const modalContext = useContext(ModalContext);

  const [units, setUnits] = useState<UnitDto[]>([]);
  const [unitsLoading, setUnitsLoading] = useState(true);
  const [conversions, setConversions] = useState<UnitConversionDto[]>([]);
  const [conversionsLoading, setConversionsLoading] = useState(true);
  const [showGenerated, setShowGenerated] = useState(false);
  const [deleting, setDeleting] = useState<Record<string, boolean>>({});

  const reloadUnits = useCallback(() => fetchUnits(workspaceId, setUnits, setUnitsLoading), [workspaceId]);
  const reloadConversions = useCallback(() => fetchUnitConversions(workspaceId, setConversionsLoading, setConversions), [workspaceId]);

  useEffect(() => {
    reloadUnits();
    reloadConversions();
  }, [reloadUnits, reloadConversions]);

  const unitName = (unitId: string) => userContext.getTranslation(units.find((unit) => unit.id == unitId)?.name ?? 'N/A');

  const runDelete = async (id: string, request: () => Promise<unknown>, onDone: () => void) => {
    if (deleting[id]) return;
    setDeleting((previous) => ({ ...previous, [id]: true }));
    try {
      await request();
      onDone();
      alertService.success(t('common:success.deleted'));
    } catch (error) {
      alertApiV1Error(error, t('errors:delete'));
    } finally {
      setDeleting((previous) => ({ ...previous, [id]: false }));
    }
  };

  const manualConversions = conversions.filter((conversion) => !conversion.autoGenerated);
  const generatedConversions = conversions
    .filter((conversion) => conversion.autoGenerated)
    .sort((a, b) => a.fromUnitId.localeCompare(b.fromUnitId) || a.toUnitId.localeCompare(b.toUnitId));

  const conversionRow = (conversion: UnitConversionDto, editable: boolean) => (
    <TableRow key={`unit-conversion-${conversion.id}`}>
      <TableCell>{unitName(conversion.fromUnitId)}</TableCell>
      <TableCell className="text-right">{formatFactor(conversion.factor)}</TableCell>
      <TableCell>{unitName(conversion.toUnitId)}</TableCell>
      <TableCell className="text-base-content/70">
        {t('settings:conversionEquals', {
          to: unitName(conversion.toUnitId),
          factor: formatFactor(1 / conversion.factor),
          from: unitName(conversion.fromUnitId),
        })}
      </TableCell>
      <TableCell>
        {editable ? (
          <div className="flex justify-end gap-2">
            <Button
              type="button"
              variant="outline"
              size="sm"
              onClick={() =>
                modalContext.openModal(
                  <UnitConversionModal units={units} existingConversions={[conversion]} onSaved={reloadConversions} unitConversion={conversion} />,
                )
              }
            >
              {t('common:edit')}
            </Button>
            <Button
              type="button"
              variant="outline-error"
              size="sm"
              aria-label={`${t('common:delete')}: ${t('settings:conversionTo', { from: unitName(conversion.fromUnitId), to: unitName(conversion.toUnitId) })}`}
              disabled={deleting[conversion.id] ?? false}
              onClick={() =>
                modalContext.openModal(
                  <DeleteConfirmationModal
                    spelling={'DELETE'}
                    entityName={t('settings:conversionTo', { from: unitName(conversion.fromUnitId), to: unitName(conversion.toUnitId) })}
                    onApprove={() => runDelete(conversion.id, () => deleteUnitConversion(workspaceId, conversion.id), reloadConversions)}
                  />,
                )
              }
            >
              {deleting[conversion.id] ? <Loading size="sm" /> : <FaTrashAlt aria-hidden />}
            </Button>
          </div>
        ) : null}
      </TableCell>
    </TableRow>
  );

  return (
    <>
      <SettingsSection
        title={t('settings:units')}
        description={t('settings:unitsHelp')}
        actions={
          <Button type="button" variant="primary" size="sm" onClick={() => modalContext.openModal(<UnitModal unit={undefined} onSaved={reloadUnits} />)}>
            <FaPlus aria-hidden />
            {t('common:add')}
          </Button>
        }
      >
        <div className="overflow-x-auto rounded-xl border border-base-300/60">
          <Table zebra className="w-full table-auto">
            <TableHead>
              <TableRow>
                <TableHeaderCell>{t('settings:key')}</TableHeaderCell>
                <EntityTranslationHeaderCells locales={labelLocales} />
                <TableHeaderCell>
                  <span className="sr-only">{t('common:actions')}</span>
                </TableHeaderCell>
              </TableRow>
            </TableHead>
            <TableBody>
              {unitsLoading ? (
                <SkeletonTableRows columns={2 + labelLocales.length} rows={4} avatarColumn={-1} />
              ) : units.length == 0 ? (
                <TableRow>
                  <TableCell colSpan={2 + labelLocales.length} className="text-center">
                    {t('common:emptyEntriesPresent')}
                  </TableCell>
                </TableRow>
              ) : (
                units.map((unit) => (
                  <TableRow key={`unit-${unit.id}`}>
                    <TableCell>{unit.name}</TableCell>
                    <EntityTranslationCells translationKey={unit.name} locales={labelLocales} />
                    <TableCell>
                      <div className="flex justify-end gap-2">
                        <Button
                          type="button"
                          variant="outline"
                          size="sm"
                          onClick={() => modalContext.openModal(<UnitModal unit={unit} onSaved={reloadUnits} />)}
                        >
                          {t('common:edit')}
                        </Button>
                        <Button
                          type="button"
                          variant="outline-error"
                          size="sm"
                          aria-label={`${t('common:delete')}: ${userContext.getTranslation(unit.name)}`}
                          disabled={deleting[unit.id] ?? false}
                          onClick={() =>
                            modalContext.openModal(
                              <DeleteConfirmationModal
                                spelling={'DELETE'}
                                entityName={userContext.getTranslation(unit.name)}
                                onApprove={() =>
                                  runDelete(
                                    unit.id,
                                    () => deleteUnit(workspaceId, unit.id),
                                    () => {
                                      reloadUnits();
                                      reloadConversions();
                                    },
                                  )
                                }
                              />,
                            )
                          }
                        >
                          {deleting[unit.id] ? <Loading size="sm" /> : <FaTrashAlt aria-hidden />}
                        </Button>
                      </div>
                    </TableCell>
                  </TableRow>
                ))
              )}
            </TableBody>
          </Table>
        </div>
      </SettingsSection>

      <SettingsSection
        title={t('settings:conversions')}
        description={t('settings:conversionsHelp')}
        actions={
          <Button
            type="button"
            variant="primary"
            size="sm"
            disabled={unitsLoading}
            onClick={() => modalContext.openModal(<UnitConversionModal units={units} existingConversions={conversions} onSaved={reloadConversions} />)}
          >
            <FaPlus aria-hidden />
            {t('common:add')}
          </Button>
        }
      >
        <div className="overflow-x-auto rounded-xl border border-base-300/60">
          <Table zebra className="w-full">
            <TableHead>
              <TableRow>
                <TableHeaderCell>{t('settings:unitA')}</TableHeaderCell>
                <TableHeaderCell className="text-right">{t('settings:unitFactor')}</TableHeaderCell>
                <TableHeaderCell>{t('settings:unitB')}</TableHeaderCell>
                <TableHeaderCell>
                  <span className="sr-only">{t('settings:recipes.conversionReverse')}</span>
                </TableHeaderCell>
                <TableHeaderCell>
                  <span className="sr-only">{t('common:actions')}</span>
                </TableHeaderCell>
              </TableRow>
            </TableHead>
            <TableBody>
              {conversionsLoading || unitsLoading ? (
                <SkeletonTableRows columns={5} rows={3} avatarColumn={-1} />
              ) : manualConversions.length == 0 ? (
                <TableRow>
                  <TableCell colSpan={5} className="text-center">
                    {t('common:emptyEntriesPresent')}
                  </TableCell>
                </TableRow>
              ) : (
                manualConversions.map((conversion) => conversionRow(conversion, true))
              )}
              {showGenerated && !conversionsLoading && !unitsLoading ? generatedConversions.map((conversion) => conversionRow(conversion, false)) : null}
            </TableBody>
          </Table>
        </div>
        {generatedConversions.length > 0 ? (
          <Button
            type="button"
            variant="ghost"
            size="sm"
            className="self-start"
            aria-expanded={showGenerated}
            onClick={() => setShowGenerated((previous) => !previous)}
          >
            <FaChevronDown aria-hidden className={cn('transition-transform motion-reduce:transition-none', showGenerated && 'rotate-180')} />
            {`${t('settings:autoGeneratedConversions')} (${generatedConversions.length}) – ${showGenerated ? t('common:hide') : t('common:show')}`}
          </Button>
        ) : null}
      </SettingsSection>
    </>
  );
}
