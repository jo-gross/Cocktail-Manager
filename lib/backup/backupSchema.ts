export type BackupImportData = z.infer<typeof BackupImportSchema>;

export interface BackupReferenceIssue {
  collection: string;
  index: number;
  field: string;
  message: string;
}

const MAX_REPORTED_ISSUES = 100;

/**
 * Checks that every required reference inside the backup points to a record of the
 * backup itself (missing ones crashed the old import half-way). Optional references
 * (calculation group, tag category, guest menu source card, slide menu) fall back to
 * null, and child rows of missing parents (images, volumes, translations,
 * conversions) are dropped, as before.
 */
export function findBackupReferenceIssues(data: BackupImportData): BackupReferenceIssue[] {
  const issues: BackupReferenceIssue[] = [];
  const ids = <T extends { id: string }>(rows: T[] | undefined) => new Set((rows ?? []).map((row) => row.id));
  const glasses = ids(data.glass);
  const ices = ids(data.ice);
  const cocktails = ids(data.cocktailRecipe);
  const steps = ids(data.cocktailRecipeStep);
  const actions = ids(data.stepActions);
  const garnishes = ids(data.garnish);
  const ingredients = ids(data.ingredient);
  const cards = ids(data.cocktailCard);
  const cardGroups = ids(data.cocktailCardGroup);
  const calculations = ids(data.calculation);

  const unique = (collection: string, rows: Array<{ id: string }> | undefined) => {
    const seen = new Set<string>();
    (rows ?? []).forEach((row, index) => {
      if (seen.has(row.id) && issues.length < MAX_REPORTED_ISSUES)
        issues.push({ collection, index, field: 'id', message: `Duplicate id "${row.id.slice(0, 64)}"` });
      seen.add(row.id);
    });
  };
  const keyed: Array<[string, Array<{ id: string }> | undefined]> = [
    ['units', data.units],
    ['stepActions', data.stepActions],
    ['garnish', data.garnish],
    ['ingredient', data.ingredient],
    ['glass', data.glass],
    ['ice', data.ice],
    ['cocktailRecipe', data.cocktailRecipe],
    ['cocktailRecipeStep', data.cocktailRecipeStep],
    ['cocktailCard', data.cocktailCard],
    ['cocktailCardGroup', data.cocktailCardGroup],
    ['calculation', data.calculation],
    ['calculationGroups', data.calculationGroups],
    ['tagCategories', data.tagCategories],
    ['guestMenus', data.guestMenus],
    ['guestMenuTemplates', data.guestMenuTemplates],
  ];
  for (const [collection, rows] of keyed) unique(collection, rows);

  const check = (collection: string, index: number, field: string, value: string | null | undefined, known: Set<string>) => {
    if (value != null && !known.has(value) && issues.length < MAX_REPORTED_ISSUES) {
      issues.push({ collection, index, field, message: `Unknown ${field} "${value.slice(0, 64)}"` });
    }
  };

  data.cocktailRecipe.forEach((cocktail, index) => {
    check('cocktailRecipe', index, 'glassId', cocktail.glassId, glasses);
    if (cocktail.iceId != null && !cocktail.glassWithIce) check('cocktailRecipe', index, 'iceId', cocktail.iceId, ices);
  });
  data.cocktailRecipeStep.forEach((step, index) => {
    check('cocktailRecipeStep', index, 'cocktailRecipeId', step.cocktailRecipeId, cocktails);
    check('cocktailRecipeStep', index, 'actionId', step.actionId, actions);
    if (step.actionId == null && !step.tool && issues.length < MAX_REPORTED_ISSUES) {
      issues.push({ collection: 'cocktailRecipeStep', index, field: 'actionId', message: 'Step without action' });
    }
  });
  data.cocktailRecipeGarnish.forEach((garnish, index) => {
    check('cocktailRecipeGarnish', index, 'cocktailRecipeId', garnish.cocktailRecipeId, cocktails);
    check('cocktailRecipeGarnish', index, 'garnishId', garnish.garnishId, garnishes);
  });
  data.cocktailRecipeIngredient.forEach((ingredient, index) => {
    check('cocktailRecipeIngredient', index, 'cocktailRecipeStepId', ingredient.cocktailRecipeStepId, steps);
    check('cocktailRecipeIngredient', index, 'ingredientId', ingredient.ingredientId, ingredients);
  });
  data.cocktailCardGroup.forEach((group, index) => check('cocktailCardGroup', index, 'cocktailCardId', group.cocktailCardId, cards));
  data.cocktailCardGroupItem.forEach((item, index) => {
    check('cocktailCardGroupItem', index, 'cocktailCardGroupId', item.cocktailCardGroupId, cardGroups);
    check('cocktailCardGroupItem', index, 'cocktailId', item.cocktailId, cocktails);
  });
  data.calculationItems.forEach((item, index) => {
    check('calculationItems', index, 'calculationId', item.calculationId, calculations);
    check('calculationItems', index, 'cocktailId', item.cocktailId, cocktails);
  });
  return issues;
}
