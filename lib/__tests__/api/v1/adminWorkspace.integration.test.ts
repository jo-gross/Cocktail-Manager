import { describe, expect, it } from 'vitest';
import adminWorkspaceHandler from '../../../../pages/api/admin/workspace';
import adminWorkspacesHandler from '../../../../pages/api/admin/workspaces';
import chromiumStatusHandler from '../../../../pages/api/chromium-status';
import prisma from '../../../../prisma/prisma';
import { invokeHandler } from '@test/helpers/invokeHandler';
import { asMasterKey, bearerToken, sessionCookie } from '@test/helpers/authFixtures';
import { seedApiKey, seedWorkspace } from '@test/helpers/dbFixtures';
import { errorCodeOf } from '@test/helpers/scenario';

describe.each([
  ['/api/admin/workspace', adminWorkspaceHandler],
  ['/api/admin/workspaces', adminWorkspacesHandler],
] as const)('%s (master key only)', (_path, handler) => {
  it('creates an empty workspace with defaults and a join code', async () => {
    const result = await invokeHandler(handler, { method: 'POST', body: { name: '  Bar  ' }, headers: asMasterKey() });
    expect(result.status).toBe(200);
    const data = (result.json as { data: { workspace: { id: string; name: string }; joinCode: string } }).data;
    expect(data.workspace.name).toBe('Bar');
    expect(data.joinCode).toMatch(/^[a-z0-9]{6}$/);

    const workspaceId = data.workspace.id;
    expect(await prisma.workspaceUser.count({ where: { workspaceId } })).toBe(0);
    expect(await prisma.workspaceJoinCode.count({ where: { workspaceId, code: data.joinCode } })).toBe(1);
    expect(await prisma.unit.count({ where: { workspaceId } })).toBe(8);
    expect(await prisma.ice.count({ where: { workspaceId } })).toBe(3);
    expect(await prisma.tagCategory.count({ where: { workspaceId } })).toBeGreaterThan(0);
    expect(await prisma.unitConversion.count({ where: { workspaceId, autoGenerated: true } })).toBeGreaterThan(0);
  });

  it('rejects sessions, workspace API keys and anonymous callers', async () => {
    const seeded = await seedWorkspace({ users: [{ role: 'OWNER' }] });
    const owner = seeded.users[0]!;
    const key = await seedApiKey(seeded.workspace.id, owner.user.id, ['WORKSPACE_UPDATE']);
    for (const headers of [{}, sessionCookie(owner.sessionToken), bearerToken(key.jwt), bearerToken('ck_master_wrong_key_123456789')]) {
      const result = await invokeHandler(handler, { method: 'POST', body: { name: 'Nope' }, headers });
      expect(result.status).toBe(401);
      expect(errorCodeOf(result)).toBe('UNAUTHORIZED');
    }
    expect(await prisma.workspace.count()).toBe(1);
  });

  it('validates the body and answers wrong methods with 405', async () => {
    for (const body of [{}, { name: '' }, { name: '   ' }, { name: 42 }, { name: 'x'.repeat(201) }]) {
      const result = await invokeHandler(handler, { method: 'POST', body, headers: asMasterKey() });
      expect(result.status).toBe(400);
    }
    expect((await invokeHandler(handler, { method: 'GET', headers: asMasterKey() })).status).toBe(405);
    expect(await prisma.workspace.count()).toBe(0);
  });
});

describe('/api/chromium-status', () => {
  it('returns only a boolean and allows GET only', async () => {
    const result = await invokeHandler(chromiumStatusHandler, { method: 'GET' });
    expect(result.status).toBe(200);
    expect(Object.keys(result.json as object)).toEqual(['available']);
    expect((await invokeHandler(chromiumStatusHandler, { method: 'POST' })).status).toBe(405);
  });
});
