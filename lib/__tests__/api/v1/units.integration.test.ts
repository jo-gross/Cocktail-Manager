import { describe, it, expect } from 'vitest';
import prisma from '../../../../prisma/prisma';
import { collectionHandler, itemHandler, conversionsCollectionHandler, conversionsItemHandler } from '@lib/api/v1/units';
import { regenerateUnitConversions } from '@lib/api/controllers/units';
import { callAs, dataOf, errorCodeOf, roleUser, seedTenantPair } from '@test/helpers/scenario';
import { seedApiKey } from '@test/helpers/dbFixtures';
import { conversionPairs, readTranslationBlob, seedAction, seedCocktailUsing, seedConversion, seedUnit } from '@test/helpers/fixtures/g4';
import type { UnitConversionDto } from '@lib/schemas/units';

describe('units v1 integration', () => {
  describe('conversions', () => {
    it('creates a manual conversion and derives inverse and transitive conversions', async () => {
      const { a } = await seedTenantPair();
      const admin = roleUser(a, 'ADMIN');
      const ws = a.workspace.id;
      const ml = await seedUnit(ws, 'ml');
      const cl = await seedUnit(ws, 'cl');
      const l = await seedUnit(ws, 'l');

      const first = await callAs(admin, conversionsCollectionHandler, {
        method: 'POST',
        query: { workspaceId: ws },
        body: { fromUnitId: cl.id, toUnitId: ml.id, factor: 10 },
      });
      expect(first.status).toBe(200);

      const second = await callAs(admin, conversionsCollectionHandler, {
        method: 'POST',
        query: { workspaceId: ws },
        body: { fromUnitId: l.id, toUnitId: cl.id, factor: 100 },
      });
      expect(second.status).toBe(200);
      const all = dataOf<UnitConversionDto[]>(second);
      expect(all).toHaveLength(6);

      const factor = (from: string, to: string) => all.find((c) => c.fromUnitId === from && c.toUnitId === to);
      expect(factor(l.id, ml.id)).toMatchObject({ factor: 1000, autoGenerated: true });
      expect(factor(ml.id, l.id)?.factor).toBeCloseTo(0.001);
      expect(factor(ml.id, cl.id)).toMatchObject({ factor: 0.1, autoGenerated: true });
      expect(factor(cl.id, ml.id)).toMatchObject({ factor: 10, autoGenerated: false });

      const { keys } = await conversionPairs(ws);
      expect(new Set(keys).size).toBe(keys.length);
    });

    it('replaces an auto-generated row when a manual conversion for the pair is created', async () => {
      const { a } = await seedTenantPair();
      const admin = roleUser(a, 'ADMIN');
      const ws = a.workspace.id;
      const [u1, u2, u3] = [await seedUnit(ws), await seedUnit(ws), await seedUnit(ws)];
      await seedConversion(ws, u1.id, u2.id, 2);
      await seedConversion(ws, u2.id, u3.id, 3);
      await regenerateUnitConversions(ws);
      expect(await prisma.unitConversion.findFirst({ where: { fromUnitId: u1.id, toUnitId: u3.id } })).toMatchObject({ autoGenerated: true, factor: 6 });

      const result = await callAs(admin, conversionsCollectionHandler, {
        method: 'POST',
        query: { workspaceId: ws },
        body: { fromUnitId: u1.id, toUnitId: u3.id, factor: 7 },
      });
      expect(result.status).toBe(200);

      const { rows, keys } = await conversionPairs(ws);
      expect(new Set(keys).size).toBe(keys.length);
      expect(rows).toHaveLength(6);
      expect(rows.find((c) => c.fromUnitId === u1.id && c.toUnitId === u3.id)).toMatchObject({ autoGenerated: false, factor: 7 });
      expect(rows.find((c) => c.fromUnitId === u3.id && c.toUnitId === u1.id)?.factor).toBeCloseTo(1 / 7);
    });

    it('rejects a second manual conversion for the same pair (either direction) with 409', async () => {
      const { a } = await seedTenantPair();
      const admin = roleUser(a, 'ADMIN');
      const ws = a.workspace.id;
      const [u1, u2] = [await seedUnit(ws), await seedUnit(ws)];
      await seedConversion(ws, u1.id, u2.id, 2);

      for (const body of [
        { fromUnitId: u1.id, toUnitId: u2.id, factor: 5 },
        { fromUnitId: u2.id, toUnitId: u1.id, factor: 5 },
      ]) {
        const result = await callAs(admin, conversionsCollectionHandler, { method: 'POST', query: { workspaceId: ws }, body });
        expect(result.status).toBe(409);
        expect(errorCodeOf(result)).toBe('UNIT_CONVERSION_EXISTS');
      }
      expect(await prisma.unitConversion.findMany({ where: { workspaceId: ws, autoGenerated: false } })).toHaveLength(1);
    });

    it('validates factor and distinct units', async () => {
      const { a } = await seedTenantPair();
      const admin = roleUser(a, 'ADMIN');
      const ws = a.workspace.id;
      const [u1, u2] = [await seedUnit(ws), await seedUnit(ws)];
      for (const body of [
        { fromUnitId: u1.id, toUnitId: u2.id, factor: 0 },
        { fromUnitId: u1.id, toUnitId: u2.id, factor: -1 },
        { fromUnitId: u1.id, toUnitId: u1.id, factor: 2 },
      ]) {
        const result = await callAs(admin, conversionsCollectionHandler, { method: 'POST', query: { workspaceId: ws }, body });
        expect(result.status).toBe(400);
      }
      expect(await prisma.unitConversion.count({ where: { workspaceId: ws } })).toBe(0);
    });

    it('updates and deletes manual conversions and regenerates the derived ones', async () => {
      const { a } = await seedTenantPair();
      const admin = roleUser(a, 'ADMIN');
      const ws = a.workspace.id;
      const [u1, u2] = [await seedUnit(ws), await seedUnit(ws)];
      const manual = await seedConversion(ws, u1.id, u2.id, 2);
      await regenerateUnitConversions(ws);

      const updated = await callAs(admin, conversionsItemHandler, {
        method: 'PUT',
        query: { workspaceId: ws, unitConversionId: manual.id },
        body: { factor: 4 },
      });
      expect(updated.status).toBe(200);
      expect(await prisma.unitConversion.findFirst({ where: { fromUnitId: u2.id, toUnitId: u1.id } })).toMatchObject({ autoGenerated: true, factor: 0.25 });

      const deleted = await callAs(admin, conversionsItemHandler, { method: 'DELETE', query: { workspaceId: ws, unitConversionId: manual.id } });
      expect(deleted.status).toBe(200);
      expect(await prisma.unitConversion.count({ where: { workspaceId: ws } })).toBe(0);
    });

    it('rejects editing or deleting auto-generated conversions with 409', async () => {
      const { a } = await seedTenantPair();
      const admin = roleUser(a, 'ADMIN');
      const ws = a.workspace.id;
      const [u1, u2] = [await seedUnit(ws), await seedUnit(ws)];
      await seedConversion(ws, u1.id, u2.id, 2);
      await regenerateUnitConversions(ws);
      const auto = await prisma.unitConversion.findFirstOrThrow({ where: { workspaceId: ws, autoGenerated: true } });

      const put = await callAs(admin, conversionsItemHandler, { method: 'PUT', query: { workspaceId: ws, unitConversionId: auto.id }, body: { factor: 9 } });
      expect(put.status).toBe(409);
      expect(errorCodeOf(put)).toBe('AUTO_GENERATED_CONVERSION');
      const del = await callAs(admin, conversionsItemHandler, { method: 'DELETE', query: { workspaceId: ws, unitConversionId: auto.id } });
      expect(del.status).toBe(409);
      expect(await prisma.unitConversion.findUnique({ where: { id: auto.id } })).toMatchObject({ factor: 0.5 });
    });

    it('serializes concurrent creates: every pair exists exactly once', async () => {
      const { a } = await seedTenantPair();
      const admin = roleUser(a, 'ADMIN');
      const ws = a.workspace.id;
      const hub = await seedUnit(ws);
      const spokes = [];
      for (let i = 0; i < 10; i++) spokes.push(await seedUnit(ws));

      const results = await Promise.all(
        spokes.map((spoke, index) =>
          callAs(admin, conversionsCollectionHandler, {
            method: 'POST',
            query: { workspaceId: ws },
            body: { fromUnitId: hub.id, toUnitId: spoke.id, factor: index + 2 },
          }),
        ),
      );
      expect(results.map((result) => result.status)).toEqual(Array(10).fill(200));

      const { rows, keys } = await conversionPairs(ws);
      expect(new Set(keys).size).toBe(keys.length);
      expect(rows).toHaveLength(11 * 10);
      expect(rows.filter((row) => !row.autoGenerated)).toHaveLength(10);
    });

    it('concurrent regenerateUnitConversions calls leave one consistent set', async () => {
      const { a } = await seedTenantPair();
      const ws = a.workspace.id;
      const units = [];
      for (let i = 0; i < 5; i++) units.push(await seedUnit(ws));
      for (let i = 0; i < 4; i++) await seedConversion(ws, units[i].id, units[i + 1].id, 2);

      await Promise.all(Array.from({ length: 10 }, () => regenerateUnitConversions(ws)));

      const { rows, keys } = await conversionPairs(ws);
      expect(new Set(keys).size).toBe(keys.length);
      expect(rows).toHaveLength(5 * 4);
      expect(rows.find((row) => row.fromUnitId === units[0].id && row.toUnitId === units[4].id)?.factor).toBe(16);
    });
  });

  describe('tenant isolation', () => {
    it('rejects tenant B unit ids in a conversion body with 400 and writes nothing', async () => {
      const { a, b } = await seedTenantPair();
      const own = await seedUnit(a.workspace.id);
      const foreign = await seedUnit(b.workspace.id);

      const result = await callAs(roleUser(a, 'OWNER'), conversionsCollectionHandler, {
        method: 'POST',
        query: { workspaceId: a.workspace.id },
        body: { fromUnitId: own.id, toUnitId: foreign.id, factor: 2 },
      });
      expect(result.status).toBe(400);
      expect(errorCodeOf(result)).toBe('INVALID_REFERENCE');
      expect(await prisma.unitConversion.count()).toBe(0);
    });

    it('returns 404 for tenant B conversion and unit ids in the path and leaves them unchanged', async () => {
      const { a, b } = await seedTenantPair();
      const owner = roleUser(a, 'OWNER');
      const [b1, b2] = [await seedUnit(b.workspace.id), await seedUnit(b.workspace.id)];
      const conversion = await seedConversion(b.workspace.id, b1.id, b2.id, 3);

      const put = await callAs(owner, conversionsItemHandler, {
        method: 'PUT',
        query: { workspaceId: a.workspace.id, unitConversionId: conversion.id },
        body: { factor: 99 },
      });
      expect(put.status).toBe(404);
      const del = await callAs(owner, conversionsItemHandler, { method: 'DELETE', query: { workspaceId: a.workspace.id, unitConversionId: conversion.id } });
      expect(del.status).toBe(404);
      const unitDel = await callAs(owner, itemHandler, { method: 'DELETE', query: { workspaceId: a.workspace.id, unitId: b1.id } });
      expect(unitDel.status).toBe(404);

      expect(await prisma.unitConversion.findUnique({ where: { id: conversion.id } })).toMatchObject({ factor: 3 });
      expect(await prisma.unit.count({ where: { workspaceId: b.workspace.id } })).toBe(2);
    });

    it('lists only own units and conversions', async () => {
      const { a, b } = await seedTenantPair();
      await seedUnit(a.workspace.id, 'own');
      await seedUnit(b.workspace.id, 'foreign');
      const result = await callAs(roleUser(a, 'USER'), collectionHandler, { method: 'GET', query: { workspaceId: a.workspace.id } });
      expect(dataOf<Array<{ name: string }>>(result).map((unit) => unit.name)).toEqual(['own']);
    });
  });

  describe('units', () => {
    it('creates a unit and its translations together', async () => {
      const { a } = await seedTenantPair();
      const ws = a.workspace.id;
      const result = await callAs(roleUser(a, 'ADMIN'), collectionHandler, {
        method: 'POST',
        query: { workspaceId: ws },
        body: { name: 'cl', translations: { en: 'Centiliter' } },
      });
      expect(result.status).toBe(200);
      expect((await readTranslationBlob(ws)).en.cl).toBe('Centiliter');
    });

    it('writes no translation when the unit create fails (duplicate name)', async () => {
      const { a } = await seedTenantPair();
      const ws = a.workspace.id;
      await seedUnit(ws, 'cl');
      const result = await callAs(roleUser(a, 'ADMIN'), collectionHandler, {
        method: 'POST',
        query: { workspaceId: ws },
        body: { name: 'cl', translations: { en: 'Centiliter' } },
      });
      expect(result.status).toBe(409);
      expect(await readTranslationBlob(ws)).toEqual({});
    });

    it('refuses to delete a unit used by a cocktail with 409 UNIT_IN_USE', async () => {
      const { a } = await seedTenantPair();
      const ws = a.workspace.id;
      const unit = await seedUnit(ws);
      const action = await seedAction(ws);
      const cocktail = await seedCocktailUsing(ws, { actionId: action.id, unitId: unit.id });

      const result = await callAs(roleUser(a, 'ADMIN'), itemHandler, { method: 'DELETE', query: { workspaceId: ws, unitId: unit.id } });
      expect(result.status).toBe(409);
      expect(errorCodeOf(result)).toBe('UNIT_IN_USE');
      expect(result.json).toMatchObject({ error: { issues: { cocktails: [{ id: cocktail.id }] } } });
      expect(await prisma.unit.findUnique({ where: { id: unit.id } })).not.toBeNull();
    });

    it('deleting a unit regenerates conversions that went through it', async () => {
      const { a } = await seedTenantPair();
      const ws = a.workspace.id;
      const [u1, u2, u3] = [await seedUnit(ws), await seedUnit(ws), await seedUnit(ws)];
      await seedConversion(ws, u1.id, u2.id, 2);
      await seedConversion(ws, u2.id, u3.id, 3);
      await regenerateUnitConversions(ws);
      expect(await prisma.unitConversion.count({ where: { workspaceId: ws } })).toBe(6);

      const result = await callAs(roleUser(a, 'ADMIN'), itemHandler, { method: 'DELETE', query: { workspaceId: ws, unitId: u2.id } });
      expect(result.status).toBe(200);
      expect(await prisma.unitConversion.count({ where: { workspaceId: ws } })).toBe(0);
    });
  });

  describe('authorization', () => {
    it('rejects writes for MANAGER and for a read-only API key', async () => {
      const { a } = await seedTenantPair();
      const ws = a.workspace.id;
      const [u1, u2] = [await seedUnit(ws), await seedUnit(ws)];
      const body = { fromUnitId: u1.id, toUnitId: u2.id, factor: 2 };

      const manager = await callAs(roleUser(a, 'MANAGER'), conversionsCollectionHandler, { method: 'POST', query: { workspaceId: ws }, body });
      expect(manager.status).toBe(403);

      const key = await seedApiKey(ws, roleUser(a, 'OWNER').user.id, ['UNITS_READ']);
      const readOnly = await callAs({ apiKeyJwt: key.jwt }, conversionsCollectionHandler, { method: 'POST', query: { workspaceId: ws }, body });
      expect(readOnly.status).toBe(403);
      const list = await callAs({ apiKeyJwt: key.jwt }, conversionsCollectionHandler, { method: 'GET', query: { workspaceId: ws } });
      expect(list.status).toBe(200);

      expect(await prisma.unitConversion.count()).toBe(0);
    });
  });
});
