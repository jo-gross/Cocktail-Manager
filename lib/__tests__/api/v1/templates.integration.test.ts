describe('admin templates API (master key)', () => {
  it('lists, updates (one default per kind), protects built-ins and template workspaces', async () => {
    await ensureBuiltInTemplates({ force: true });
    const catalog = await seedCatalogWorkspace();
    const created = await markAsTemplate(catalog.workspaceId, 'classics', false);
    expect(created).toMatchObject({ key: 'classics', builtIn: false, published: false, memberCount: 0 });
    const second = await seedCatalogWorkspace();
    await markAsTemplate(second.workspaceId, 'tiki');

    const list = await invokeHandler(adminTemplatesHandler, { method: 'GET', headers: asMasterKey() });
    expect(dataOf<AdminTemplateDto[]>(list).map((template) => template.key)).toEqual(expect.arrayContaining(['base', 'classics', 'tiki']));

    const patch = (key: string, body: unknown) => invokeHandler(adminTemplateItemHandler, { method: 'PATCH', headers: asMasterKey(), query: { key }, body });
    expect((await patch('classics', { isDefault: true, published: true })).status).toBe(200);
    expect((await patch('tiki', { isDefault: true })).status).toBe(200);
    expect(await prisma.workspaceTemplate.findMany({ where: { kind: 'CATALOG', isDefault: true }, select: { key: true } })).toEqual([{ key: 'tiki' }]);
    expect((await patch('nope', { published: true })).status).toBe(404);

    const duplicate = await invokeHandler(adminTemplatesHandler, {
      method: 'POST',
      headers: asMasterKey(),
      body: { workspaceId: catalog.workspaceId, key: 'other', kind: 'CATALOG', name: { de: 'X' }, locales: ['de'] },
    });
    expect(errorCodeOf(duplicate)).toBe('ALREADY_TEMPLATE');

    // Marked workspaces cannot be deleted.
    const owner = await prisma.user.create({ data: { name: 'Owner', email: 'owner-tpl@test.local' } });
    await prisma.workspaceUser.create({ data: { workspaceId: catalog.workspaceId, userId: owner.id, role: 'OWNER' } });
    await prisma.session.create({ data: { token: 'tpl-owner-session', userId: owner.id, expiresAt: new Date(Date.now() + 3_600_000) } });
    const blocked = await invokeHandler(workspaceItemHandler, {
      method: 'DELETE',
      headers: sessionCookie('tpl-owner-session'),
      query: { workspaceId: catalog.workspaceId },
    });
    expect(blocked.status).toBe(409);
    expect(errorCodeOf(blocked)).toBe('TEMPLATE_IN_USE');

    const builtInDelete = await invokeHandler(adminTemplateItemHandler, { method: 'DELETE', headers: asMasterKey(), query: { key: 'base' } });
    expect(builtInDelete.status).toBe(409);
    expect(errorCodeOf(builtInDelete)).toBe('BUILT_IN_TEMPLATE');
    const unmark = await invokeHandler(adminTemplateItemHandler, { method: 'DELETE', headers: asMasterKey(), query: { key: 'classics' } });
    expect(unmark.status).toBe(200);
    expect(
      (
        await invokeHandler(workspaceItemHandler, {
          method: 'DELETE',
          headers: sessionCookie('tpl-owner-session'),
          query: { workspaceId: catalog.workspaceId },
        })
      ).status,
    ).toBe(200);

    // Memberless template workspaces are no demo workspaces.
    await cleanupExpiredDemoWorkspaces(new Date(Date.now() + 365 * 24 * 3_600_000));
    expect(await prisma.workspaceTemplate.count({ where: { key: { in: ['base', 'tiki'] } } })).toBe(2);

    const seeded = await seedWorkspace({ users: [{ role: 'OWNER' }] });
    for (const headers of [{}, sessionCookie(seeded.users[0]!.sessionToken)]) {
      expect((await invokeHandler(adminTemplatesHandler, { method: 'GET', headers })).status).toBe(401);
    }
  });

  it('clones a template with a one-time join code whose first user becomes owner; access only for custom templates', async () => {
    await ensureBuiltInTemplates({ force: true });
    const clone = await invokeHandler(adminCloneHandler, { method: 'POST', headers: asMasterKey(), query: { key: 'base' }, body: { key: 'my-base' } });
    expect(clone.status, JSON.stringify(clone.json)).toBe(201);
    const { template, joinCode } = dataOf<AdminTemplateAccessDto>(clone);
    expect(template).toMatchObject({ key: 'my-base', kind: 'BASE', builtIn: false, published: false, isDefault: false, memberCount: 0 });
    const base = await prisma.workspaceTemplate.findUniqueOrThrow({ where: { key: 'base' } });
    expect((await defaultsOf(template.workspaceId)).units).toEqual((await defaultsOf(base.workspaceId)).units);

    const taken = await invokeHandler(adminCloneHandler, { method: 'POST', headers: asMasterKey(), query: { key: 'base' }, body: { key: 'my-base' } });
    expect(errorCodeOf(taken)).toBe('TEMPLATE_KEY_TAKEN');

    const seeded = await seedWorkspace({ users: [{ role: 'USER' }] });
    const joiner = seeded.users[0]!;
    const joined = await invokeHandler(joinHandler, { method: 'POST', headers: sessionCookie(joiner.sessionToken), query: { code: joinCode } });
    expect(joined.status, JSON.stringify(joined.json)).toBe(200);
    expect(await prisma.workspaceUser.findFirst({ where: { workspaceId: template.workspaceId }, select: { userId: true, role: true } })).toEqual({
      userId: joiner.user.id,
      role: Role.OWNER,
    });

    const builtInAccess = await invokeHandler(adminAccessHandler, { method: 'POST', headers: asMasterKey(), query: { key: 'base' } });
    expect(errorCodeOf(builtInAccess)).toBe('BUILT_IN_TEMPLATE');
    const access = await invokeHandler(adminAccessHandler, { method: 'POST', headers: asMasterKey(), query: { key: 'my-base' } });
    expect(access.status).toBe(201);
    expect(
      await prisma.workspaceJoinCode.count({
        where: { workspaceId: template.workspaceId, code: dataOf<AdminTemplateAccessDto>(access).joinCode, onlyUseOnce: true },
      }),
    ).toBe(1);
  });
});

