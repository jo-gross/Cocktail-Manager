/** Everything the BASE template creates, without ids. */
async function defaultsOf(workspaceId: string) {
  const units = await prisma.unit.findMany({ where: { workspaceId } });
  const unitName = new Map(units.map((unit) => [unit.id, unit.name]));
  const conversions = await prisma.unitConversion.findMany({ where: { workspaceId } });
  const settings = await prisma.workspaceSetting.findMany({ where: { workspaceId } });
  return {
    units: units.map((unit) => unit.name).sort(),
    conversions: conversions
      .map((row) => `${unitName.get(row.fromUnitId)}→${unitName.get(row.toUnitId)}=${row.factor.toFixed(6)}${row.autoGenerated ? ' (auto)' : ''}`)
      .sort(),
    ice: (await prisma.ice.findMany({ where: { workspaceId } })).map((ice) => ice.name).sort(),
    actions: (await prisma.workspaceCocktailRecipeStepAction.findMany({ where: { workspaceId } }))
      .map((action) => `${action.actionGroup}:${action.name}:${action.dilutionPercent}`)
      .sort(),
    tagCategories: (await prisma.tagCategory.findMany({ where: { workspaceId }, orderBy: { order: 'asc' } })).map(({ name, order, showAsGuestFilter }) => ({
      name,
      order,
      showAsGuestFilter,
    })),
    settings: Object.fromEntries(settings.map((row) => [row.setting, row.setting === 'translations' ? JSON.parse(row.value ?? '{}') : row.value])),
  };
}

async function legacyDefaults() {
  const legacy = await createLegacyWorkspaceWithDefaults({ name: 'Legacy' });
  await regenerateUnitConversions(legacy.id);
  return defaultsOf(legacy.id);
}

/** A small catalog with a German primary language and English translations. */
async function seedCatalogWorkspace() {
  const workspace = await createWorkspace({ name: 'Katalog', locale: 'de', setupCompleted: true });
  const workspaceId = workspace.id;
  await prisma.workspaceSetting.update({
    where: { workspaceId_setting: { workspaceId, setting: 'contentLocales' } },
    data: { value: JSON.stringify({ primary: 'de', additional: ['en'] }) },
  });
  const cl = await prisma.unit.findFirstOrThrow({ where: { workspaceId, name: 'CL' } });
  const shot = await prisma.unit.create({ data: { workspaceId, name: 'SHOT' } });
  const cubes = await prisma.ice.findFirstOrThrow({ where: { workspaceId, name: 'ICE_CUBES' } });
  const shake = await prisma.workspaceCocktailRecipeStepAction.findFirstOrThrow({ where: { workspaceId, name: 'SHAKE' } });

  const glass = await prisma.glass.create({ data: { workspaceId, name: 'Coupette', deposit: 2, translations: { create: { locale: 'en', name: 'Coupe' } } } });
  const otherGlass = await prisma.glass.create({ data: { workspaceId, name: 'Tumbler', deposit: 0 } });
  const rum = await prisma.ingredient.create({
    data: {
      workspaceId,
      name: 'Weißer Rum',
      price: 20,
      abv: 40,
      guestInfoComplete: true,
      translations: { create: { locale: 'en', name: 'White Rum', description: 'Light rum' } },
    },
  });
  const lime = await prisma.ingredient.create({
    data: { workspaceId, name: 'Limettensaft', price: 3, translations: { create: { locale: 'en', name: 'Lime Juice' } } },
  });
  await prisma.ingredientVolume.create({ data: { workspaceId, ingredientId: rum.id, unitId: cl.id, volume: 70 } });
  const unused = await prisma.ingredient.create({ data: { workspaceId, name: 'Gin' } });
  const wheel = await prisma.garnish.create({
    data: { workspaceId, name: 'Limettenrad', price: 0.2, translations: { create: { locale: 'en', name: 'Lime Wheel' } } },
  });

  const daiquiri = await prisma.cocktailRecipe.create({
    data: {
      workspaceId,
      name: 'Daiquiri',
      description: 'Klassiker',
      price: 9.5,
      glassId: glass.id,
      iceId: cubes.id,
      translations: { create: { locale: 'en', description: 'Classic' } },
      garnishes: { create: { garnishId: wheel.id, garnishNumber: 0 } },
      steps: {
        create: {
          stepNumber: 0,
          actionId: shake.id,
          ingredients: {
            create: [
              { ingredientId: rum.id, ingredientNumber: 0, amount: 6, unitId: cl.id },
              { ingredientId: lime.id, ingredientNumber: 1, amount: 1, unitId: shot.id },
            ],
          },
        },
      },
    },
  });
  const card = await prisma.cocktailCard.create({
    data: {
      workspaceId,
      name: 'Sommer',
      groups: { create: { name: 'Sours', groupNumber: 0, groupPrice: 9, items: { create: { cocktailId: daiquiri.id, itemNumber: 0, specialPrice: 8 } } } },
    },
  });
  return { workspaceId, glass, otherGlass, rum, lime, unused, wheel, daiquiri, card };
}

async function markAsTemplate(workspaceId: string, key = 'classics', published = true) {
  const result = await invokeHandler(adminTemplatesHandler, {
    method: 'POST',
    headers: asMasterKey(),
    body: { workspaceId, key, kind: 'CATALOG', name: { de: 'Klassiker', en: 'Classics' }, locales: ['de', 'en'], published },
  });
  expect(result.status, JSON.stringify(result.json)).toBe(201);
  return dataOf<AdminTemplateDto>(result);
}

async function workspaceContent(workspaceId: string) {
  return {
    glasses: await prisma.glass.count({ where: { workspaceId } }),
    ingredients: await prisma.ingredient.count({ where: { workspaceId } }),
    garnishes: await prisma.garnish.count({ where: { workspaceId } }),
    cocktails: await prisma.cocktailRecipe.count({ where: { workspaceId } }),
    cards: await prisma.cocktailCard.count({ where: { workspaceId } }),
    units: await prisma.unit.count({ where: { workspaceId } }),
    settings: await prisma.workspaceSetting.findMany({ where: { workspaceId }, orderBy: { setting: 'asc' }, select: { setting: true, value: true } }),
  };
}

