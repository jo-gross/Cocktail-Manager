describe('onboarding', () => {
  it('reports the checklist and completes the setup idempotently', async () => {
    const seeded = await seedWorkspace({ users: [{ role: 'USER' }, { role: 'ADMIN' }] });
    const workspaceId = seeded.workspace.id;
    const query = { workspaceId };

    const initial = dataOf<OnboardingDto>(await callAs(roleUser(seeded, 'USER'), onboardingHandler, { method: 'GET', query }));
    expect(initial.setupCompletedAt).toBeNull();
    expect(Object.fromEntries(initial.checklist.map((item) => [item.id, item.done]))).toEqual({
      glasses: false,
      ingredients: false,
      cocktails: false,
      cards: false,
      prices: false,
      guestInfo: false,
      team: true,
      guestMenu: false,
    });

    const glass = await prisma.glass.create({ data: { workspaceId, name: 'Glass', deposit: 0 } });
    await prisma.cocktailRecipe.create({ data: { workspaceId, name: 'A', glassId: glass.id } });
    await prisma.cocktailRecipe.create({ data: { workspaceId, name: 'B', price: 5 } });
    const partial = dataOf<OnboardingDto>(await callAs(roleUser(seeded, 'USER'), onboardingHandler, { method: 'GET', query }));
    expect(partial.checklist.find((item) => item.id === 'prices')).toEqual({ id: 'prices', done: false, skipped: false, open: 1 });
    expect(partial.checklist.find((item) => item.id === 'glasses')).toEqual({ id: 'glasses', done: true, skipped: false, open: 0 });

    const completed = await callAs(roleUser(seeded, 'ADMIN'), completeHandler, { method: 'POST', query });
    expect(completed.status).toBe(200);
    const completedAt = dataOf<OnboardingDto>(completed).setupCompletedAt;
    expect(completedAt).not.toBeNull();
    const again = dataOf<OnboardingDto>(await callAs(roleUser(seeded, 'ADMIN'), completeHandler, { method: 'POST', query }));
    expect(again.setupCompletedAt).toBe(completedAt);
    expect((await callAs(roleUser(seeded, 'USER'), completeHandler, { method: 'POST', query })).status).toBe(403);

    const workspace = await callAs(roleUser(seeded, 'USER'), workspaceItemHandler, { method: 'GET', query });
    expect(dataOf<{ setupCompletedAt: string | null; isTemplate: boolean }>(workspace)).toMatchObject({ setupCompletedAt: completedAt, isTemplate: false });
  });
});

