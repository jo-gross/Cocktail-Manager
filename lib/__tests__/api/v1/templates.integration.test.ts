describe('built-in template sync', () => {
  it('is idempotent and safe in parallel', async () => {
    await Promise.all(Array.from({ length: 5 }, () => syncBuiltInTemplates()));
    await syncBuiltInTemplates();
    const keys = listBuiltInTemplateKeys();
    expect(keys).toContain('base');
    expect(await prisma.workspaceTemplate.count()).toBe(keys.length);
    expect(await prisma.workspace.count()).toBe(keys.length);
    const base = await prisma.workspaceTemplate.findUniqueOrThrow({
      where: { key: 'base' },
      include: { workspace: { include: { _count: { select: { users: true } } } } },
    });
    expect(base).toMatchObject({ builtIn: true, kind: 'BASE', isDefault: true, published: true });
    expect(base.workspace._count.users).toBe(0);
    expect(base.workspace.setupCompletedAt).not.toBeNull();
  });

  it('replaces only the built-in copy when the repo version is higher and keeps the database flags', async () => {
    await syncBuiltInTemplates();
    const before = await prisma.workspaceTemplate.update({ where: { key: 'base' }, data: { version: 0, sortOrder: 42 } });
    const custom = await seedCatalogWorkspace();
    await markAsTemplate(custom.workspaceId, 'custom');

    await syncBuiltInTemplates();
    const after = await prisma.workspaceTemplate.findUniqueOrThrow({ where: { key: 'base' } });
    expect(after.workspaceId).not.toBe(before.workspaceId);
    expect(after.version).toBeGreaterThan(0);
    expect(after.sortOrder).toBe(42);
    expect(await prisma.workspace.count({ where: { id: before.workspaceId } })).toBe(0);
    expect(await prisma.workspaceTemplate.findUniqueOrThrow({ where: { key: 'custom' } })).toMatchObject({ workspaceId: custom.workspaceId, builtIn: false });
  });

  it('every built-in template imports into a fresh workspace', async () => {
    await syncBuiltInTemplates();
    for (const key of listBuiltInTemplateKeys()) {
      const target = await createWorkspace({ name: `Target ${key}` });
      const result = await applyTemplate(target.id, key, { mode: 'all' });
      expect(result.template).toBe(key);
    }
  });
});

