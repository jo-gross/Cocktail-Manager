/**
 * Writes a workspace (maintained in the app) as built-in template into the repo:
 * `templates/<key>/manifest.json` (version + 1, or a new manifest), `backup.json`
 * (backup format, images as `file:images/<hash>.<ext>`) and `images/`.
 * Review the diff and commit; the next start replaces the database copy.
 *
 *   DATABASE_URL=… pnpm templates:pull <workspaceId> <key> [--kind CATALOG|BASE|DEMO]
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { extname, join } from 'node:path';
import prisma from '../prisma/prisma';
import { readWorkspaceBackup } from '../lib/backup/readWorkspaceBackup';
import { BackupImportSchema } from '../lib/backup/backupSchema';
import { TEMPLATES_DIR, TEMPLATE_IMAGE_MIME_TYPES, TEMPLATE_IMAGE_PREFIX } from '../lib/templates/builtIn';
import { TEMPLATE_KEY_PATTERN, TEMPLATE_KINDS, TemplateManifestSchema, type TemplateKindName, type TemplateManifest } from '../lib/templates/manifest';
import { parseContentLocales } from '../lib/workspace/workspaceLocaleSettings';

/** Row fields that only add noise to the diff (re-assigned on import anyway). */
const DROPPED_FIELDS = new Set(['workspaceId', 'createdAt', 'updatedAt', 'updatedByUserId', 'publishedAt']);
const IMAGE_FIELDS = new Set(['image', 'content']);
const EXTENSION_BY_MIME = Object.fromEntries(Object.entries(TEMPLATE_IMAGE_MIME_TYPES).map(([extension, mime]) => [mime, extension]));

function parseArgs(argv: string[]) {
  const positional = argv.filter((arg, index) => !arg.startsWith('--') && argv[index - 1] !== '--kind');
  const kindIndex = argv.indexOf('--kind');
  const kind = kindIndex >= 0 ? argv[kindIndex + 1] : undefined;
  const [workspaceId, key] = positional;
  if (!workspaceId || !key || !TEMPLATE_KEY_PATTERN.test(key) || (kind && !TEMPLATE_KINDS.includes(kind as TemplateKindName))) {
    console.error('Usage: pnpm templates:pull <workspaceId> <key> [--kind CATALOG|BASE|DEMO]');
    process.exit(1);
  }
  return { workspaceId, key, kind: kind as TemplateKindName | undefined };
}

function imageName(bytes: Buffer, extension: string): string {
  return `${createHash('sha256').update(bytes).digest('hex').slice(0, 16)}${extension}`;
}

/** Image credits follow their image to its content-addressed name; credits of images that are gone are dropped. */
function remapAttributions(attributions: Record<string, string> | undefined, imagesDir: string, images: Map<string, Buffer>) {
  if (!attributions) return undefined;
  const next: Record<string, string> = {};
  for (const [file, credit] of Object.entries(attributions)) {
    const path = join(imagesDir, file);
    const mimeType = TEMPLATE_IMAGE_MIME_TYPES[extname(file).toLowerCase()];
    if (!existsSync(path) || !mimeType) continue;
    const name = imageName(readFileSync(path), EXTENSION_BY_MIME[mimeType]!);
    if (images.has(name)) next[name] = credit;
  }
  return next;
}

/** Moves data-URI images into `images/` (content-addressed, so unchanged images keep their name). */
function extractImages(value: unknown, images: Map<string, Buffer>, field?: string): unknown {
  if (typeof value === 'string' && field && IMAGE_FIELDS.has(field)) {
    const match = /^data:([^;,]+);base64,(.*)$/s.exec(value);
    const extension = match ? EXTENSION_BY_MIME[match[1]!.toLowerCase()] : undefined;
    if (!match || !extension) return value;
    const bytes = Buffer.from(match[2]!, 'base64');
    const name = imageName(bytes, extension);
    images.set(name, bytes);
    return `${TEMPLATE_IMAGE_PREFIX}${name}`;
  }
  if (Array.isArray(value)) return value.map((item) => extractImages(item, images, field));
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => !DROPPED_FIELDS.has(key))
        .map(([key, item]) => [key, extractImages(item, images, key)]),
    );
  }
  return value;
}

async function main() {
  const { workspaceId, key, kind } = parseArgs(process.argv.slice(2));
  const workspace = await prisma.workspace.findUnique({ where: { id: workspaceId }, select: { name: true } });
  if (!workspace) throw new Error(`Workspace ${workspaceId} not found`);

  const backup = await readWorkspaceBackup(workspaceId);
  // Derived rows are regenerated on import.
  backup.unitConversions = backup.unitConversions.filter((conversion) => !conversion.autoGenerated);
  // Fails early instead of committing a template the import would reject.
  const check = BackupImportSchema.safeParse(JSON.parse(JSON.stringify(backup)));
  if (!check.success) throw new Error(`The workspace is not a valid backup: ${JSON.stringify(check.error.issues.slice(0, 5))}`);

  const images = new Map<string, Buffer>();
  const content = extractImages(JSON.parse(JSON.stringify(backup)), images);

  const dir = join(TEMPLATES_DIR, key);
  const manifestPath = join(dir, 'manifest.json');
  const contentLocales = parseContentLocales(backup.workspaceSettings.find((row) => row.setting === 'contentLocales')?.value);
  const locales = [contentLocales.primary, ...contentLocales.additional];
  let manifest: TemplateManifest;
  if (existsSync(manifestPath)) {
    const previous = TemplateManifestSchema.parse(JSON.parse(readFileSync(manifestPath, 'utf-8')));
    const attributions = remapAttributions(previous.attributions, join(dir, 'images'), images);
    manifest = { ...previous, kind: kind ?? previous.kind, version: previous.version + 1, locales, ...(attributions ? { attributions } : {}) };
  } else {
    manifest = TemplateManifestSchema.parse({ key, kind: kind ?? 'CATALOG', version: 1, name: { [locales[0]!]: workspace.name }, locales });
  }

  mkdirSync(dir, { recursive: true });
  rmSync(join(dir, 'images'), { recursive: true, force: true });
  if (images.size > 0) mkdirSync(join(dir, 'images'));
  for (const [name, bytes] of images) writeFileSync(join(dir, 'images', name), bytes);
  writeFileSync(join(dir, 'backup.json'), `${JSON.stringify(content, null, 2)}\n`);
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

  console.log(`Wrote templates/${key} (version ${manifest.version}, ${images.size} image(s)). Review the diff, then commit.`);
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
